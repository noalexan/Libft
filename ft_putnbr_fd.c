#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	static const char	base[] = "0123456789";

	if (n < 10)
		ft_putchar_fd(base[n], fd);
	else
	{
		ft_putnbr_fd(n / 10, fd);
		ft_putnbr_fd(n % 10, fd);
	}
}
